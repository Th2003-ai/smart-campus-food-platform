-- 用户组权限（禅道式：模块-方法粒度）初始化数据
-- 由 docs/gen_group_priv.py 扫描 Controller 生成，勿手改
USE campus_ai_delivery;

CREATE TABLE IF NOT EXISTS sys_group (
  id          VARCHAR(32)  NOT NULL COMMENT '用户组ID',
  code        VARCHAR(32)  NOT NULL COMMENT '组编码',
  name        VARCHAR(64)  NOT NULL COMMENT '组名称',
  builtin     TINYINT      NOT NULL DEFAULT 0 COMMENT '1=内置组',
  remark      VARCHAR(255)          DEFAULT NULL,
  create_time DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id), UNIQUE KEY uk_group_code (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户组（一人可属多组，权限取并集）';

CREATE TABLE IF NOT EXISTS sys_group_user (
  id       BIGINT      NOT NULL AUTO_INCREMENT,
  group_id VARCHAR(32) NOT NULL,
  user_id  VARCHAR(32) NOT NULL,
  PRIMARY KEY (id), UNIQUE KEY uk_group_user (group_id, user_id), KEY idx_gu_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户-用户组';

CREATE TABLE IF NOT EXISTS sys_group_priv (
  id         BIGINT      NOT NULL AUTO_INCREMENT,
  group_id   VARCHAR(32) NOT NULL COMMENT '用户组ID',
  module     VARCHAR(64) NOT NULL COMMENT '模块=控制器名，例如 dish',
  method     VARCHAR(64) NOT NULL COMMENT '方法=接口名，例如 create',
  data_scope VARCHAR(16) NOT NULL DEFAULT 'ALL' COMMENT 'ALL/SHOP/SELF',
  PRIMARY KEY (id), UNIQUE KEY uk_group_priv (group_id, module, method)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户组权限（模块-方法粒度，默认拒绝）';

